import { createRequire } from 'module';
const { chromium } = createRequire('/opt/node-tools/node_modules/')('playwright');
const browser = await chromium.launch({ executablePath: '/opt/pw-browsers/chromium-1194/chrome-linux/chrome', args: ['--use-gl=angle', '--use-angle=swiftshader', '--enable-unsafe-swiftshader', '--no-sandbox'] });
const ctx = await browser.newContext({ viewport: { width: 844, height: 390 } });
const page = await ctx.newPage();
const errs = []; page.on('pageerror', (e) => errs.push(e.message)); page.on('console', (m) => m.type() === 'error' && errs.push(m.text()));
await page.goto('http://localhost:8123/index.html'); 
await page.waitForFunction(() => navigator.serviceWorker.controller || false, null, { timeout: 15000 }).catch(() => {});
await page.evaluate(() => navigator.serviceWorker.ready);
await page.waitForTimeout(2500);
const cached = await page.evaluate(async () => { const k = await caches.keys(); const c = await caches.open(k[0]); return [k[0], (await c.keys()).length]; });
console.log('cache', cached);
await ctx.setOffline(true);
await page.reload({ waitUntil: 'load' });
await page.waitForTimeout(2500);
console.log('offline state:', await page.evaluate(() => window.__game && __game.state), 'loader gone:', await page.evaluate(() => !document.getElementById('loader')));
await page.screenshot({ path: '/tmp/s/offline.png' });
console.log(errs.length ? errs.join('\n') : 'no errors');
await browser.close();
